def caesar_encode(text,key):
    shifted=''
    for letter in text:
        new_letter=alphabet[(alphabet.index(letter)+key)%26]
        shifted+=new_letter
    return shifted


def caesar_break(text):
    text=depunctuate(text)

    best_probability=0
    best_plaintext=''
    best_shift=0
    for shift in range(26):
        probability=0
        shifted=caesar_encode(text,shift)
        for word in common_words:
            probability+=shifted.count(word)
        if probability>best_probability:
            best_probability=probability
            best_plaintext=shifted
            best_shift=shift
    return (best_shift,best_plaintext)

